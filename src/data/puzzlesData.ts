// Helper to generate Intermediate and Advanced puzzles
function createPuzzles(
  tier: 'intermediate' | 'advanced',
  items: Omit<Puzzle, 'difficulty'>[]
): Puzzle[] {
  return items.map((item) => ({
    ...item,
    difficulty: tier,
  }));
}

